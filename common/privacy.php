<h1>プライバシーポリシー</h1>

<p>当サイト（karin-archive.com / 宮本佳林・M-line・ハロプロ Archive）における情報の取扱いについて定めます。</p>

<h3>1. アクセス解析について</h3>
<p>当サイトでは、利用状況の把握のためにGoogleアナリティクス（Google Analytics）を利用しています。Googleアナリティクスはデータ収集のためにCookieを使用します。収集される情報は匿名であり、個人を特定するものではありません。収集を希望されない場合は、お使いのブラウザの設定、またはGoogleが提供するオプトアウトアドオン（<a href="https://tools.google.com/dlpage/gaoptout" target="_blank" rel="noopener">https://tools.google.com/dlpage/gaoptout</a>）により無効化できます。</p>

<h3>2. アクセスログについて</h3>
<p>当サイトはレンタルサーバー上で運用されており、サーバーの仕様により、アクセス日時・IPアドレス・ブラウザ種別等のログが自動的に記録される場合があります。これらはサイトの保守・セキュリティの目的で利用します。</p>

<h3>3. 外部サービスのCookieについて</h3>
<p>当サイトには、YouTube等の外部サービスへのリンクや埋め込みが含まれます。これらの外部サービスが独自にCookieを使用する場合があります。詳細は各サービスのプライバシーポリシーをご確認ください。</p>

<h3>4. 個人情報について</h3>
<p>当サイトは、氏名・メールアドレス等の個人情報を入力していただく機能を設けていません。</p>

<h3 id="sns-search">5. SNS投稿の検索サイト（Instagram・Threads）について</h3>
<p>当サイトの関連サイトとして、<a href="https://insta.karin-archive.com/">insta.karin-archive.com</a>（Instagram）と <a href="https://threads.karin-archive.com/">threads.karin-archive.com</a>（Threads）を運営しています。どちらも、ハロー！プロジェクトのメンバー・OGの公開アカウントの投稿を、Meta が提供する公式API（Instagram Graph API・Threads API）で取得し、日付・メンバー・本文から探せるようにしたものです。Meta およびハロー！プロジェクトとは関係のない、個人の非公式サイトです。</p>
<p>取得・保存しているのは、公開されている投稿の次の情報だけです。</p>
<ul>
  <li>投稿のID・アカウント名・投稿日時・投稿の種類・元の投稿へのリンク</li>
  <li>投稿の本文（検索のために保存します。画面には先頭の一部だけを表示し、続きは元の投稿へご案内します）</li>
</ul>
<p>画像・動画・音声、返信・いいね・フォロワーの情報は保存していません。これらのサイトにはログインの機能がなく、閲覧する方の個人情報や、検索した言葉は記録していません。アクセス解析のツールも使っていません。APIの利用に使うのは運営者自身のアカウントのアクセストークンだけで、第三者のアカウントでログインしてもらうことはありません。</p>

<h3 id="data-deletion">6. 投稿データの削除のご依頼</h3>
<p>上記のサイトに収録されている投稿の削除や、アカウントを収録の対象から外すことをご希望の場合は、ページ下部の「誤りの報告・追加のご要望」から、アカウント名（または投稿のURL）を添えてお知らせください。匿名で送信できます。確認でき次第、該当するデータをデータベースから削除し、以後は取得しません。</p>
<p>元の投稿が Instagram・Threads で削除された場合も、ご連絡いただければ同様に削除します。</p>

<h3>7. 本ポリシーの変更</h3>
<p>本ポリシーは必要に応じて予告なく変更することがあります。変更後の内容は当サイトに掲載した時点から適用されます。</p>
