<h1>プライバシーポリシー</h1>

<p>当サイト（karin-archive.com / 宮本佳林・M-line・ハロプロ Archive）における情報の取扱いについて定めます。</p>

<h3>1. アクセス解析について</h3>
<p>当サイトでは、利用状況の把握のためにGoogleアナリティクス（Google Analytics）を利用しています。Googleアナリティクスはデータ収集のためにCookieを使用します。収集される情報は匿名であり、個人を特定するものではありません。収集を希望されない場合は、お使いのブラウザの設定、またはGoogleが提供するオプトアウトアドオン（<a href="https://tools.google.com/dlpage/gaoptout" target="_blank">https://tools.google.com/dlpage/gaoptout</a>）により無効化できます。</p>

<h3>2. アクセスログについて</h3>
<p>当サイトはCloudflare, Inc. のサービス（Cloudflare Workers）上で運用されており、アクセス日時・IPアドレス・ブラウザ種別等のログが、同社のシステムで自動的に処理・記録される場合があります。当サイトの運営者がこれらのログから個人を特定することはなく、サイトの保守・セキュリティの目的でのみ利用します。</p>

<h3>3. 外部サービスについて</h3>
<p>当サイトでは、次の外部サービスを利用しています。これらのサービスには、閲覧者のIPアドレス等が送信される場合があり、各サービスが独自にCookieを使用することもあります。詳細は各サービスのプライバシーポリシーをご確認ください。</p>
<ul>
  <li>Google Fonts（Webフォントの配信）</li>
  <li>YouTube・X・Instagram・Threads等への外部リンクや動画・投稿の埋め込み</li>
  <li>Cloudflare Turnstile（下記「誤りの報告・追加のご要望」フォームのBot対策。フォームを開いたときだけ読み込みます）</li>
</ul>

<h3>4. 「誤りの報告・追加のご要望」フォームについて</h3>
<p>ページ下部のフォームは匿名で送信でき、名前・メールアドレスの入力欄はありません。送信すると、次の情報を保存します。</p>
<ul>
  <li>入力された本文、選んだ種別（誤り・追加希望・その他）</li>
  <li>送信元のページのパス、ブラウザ種別（User-Agent）、送信日時</li>
  <li>短時間の連続送信を防ぐための、IPアドレスのハッシュ値（IPアドレスそのものは保存しません。当日の日付を含めて計算するため、翌日には別の値になり、日をまたいだ追跡はできません）</li>
</ul>
<p>これらは、内容の確認と対応、スパム対策のためだけに使い、第三者への提供はしません。お返事はしませんので、連絡先や個人情報は本文に書かないでください。</p>

<h3>5. 個人情報について</h3>
<p>上記のフォームを除き、当サイトは氏名・メールアドレス等の個人情報を入力していただく機能を設けていません。</p>

<h3>6. 収録している投稿データについて</h3>
<p>当サイトは、X・Instagram・Threads等で公開されている投稿のうち、宮本佳林さんやハロー！プロジェクトに関するものの一部を、リンクや検索用のデータとして収録しています。</p>

<h3 id="data-deletion">7. 投稿データの削除のご依頼</h3>
<p>上記のサイトに収録されている投稿の削除や、アカウントを収録の対象から外すことをご希望の場合は、ページ下部の「誤りの報告・追加のご要望」から、アカウント名（または投稿のURL）を添えてお知らせください。匿名で送信できます。確認でき次第、該当するデータをデータベースから削除し、以後は取得しません。</p>
<p>元の投稿が Instagram・Threads で削除された場合も、ご連絡いただければ同様に削除します。</p>

<h3>8. 本ポリシーの変更</h3>
<p>本ポリシーは必要に応じて予告なく変更することがあります。変更後の内容は当サイトに掲載した時点から適用されます。</p>
