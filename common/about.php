<p>当サイトがまとめているのは、公開されていて、広く誰でも見られたことのある情報です。たとえば、すでに見られなくなったもの（ニコニコ動画のボカロ部のように期間限定で公開されていた動画、今は閉鎖されたブログなど）も、当時は誰もが見られたものなので、記録として残しています。見られなくなったものは、アーカイブが残っていればそちらにリンクしています。</p>

