<h1>このサイトについて</h1>

<p><strong>宮本佳林・M-line・ハロプロ Archive</strong> は、宮本佳林さんを中心に、ハロー！プロジェクトの公開されている情報を、あとから見つけやすいように整理して並べているサイトです。</p>
<p>個人が趣味で運営する非公式のファンサイトで、アップフロントグループ各社、ハロー！プロジェクト、所属アーティストおよび関係各社とは関係ありません（<a href="/common/disclaimer">免責事項</a>）。</p>

<h3>1. どういうサイトか</h3>
<ul>
  <li>動画、曲、インタビュー、出演作品、ライブのセットリストなどを、一覧にして整理しています。</li>
  <li>載せているのは、基本的にリンクと、日付や出演者などの整理した情報です。</li>
  <li>目的は「あのとき見たものを、あとから探せるようにすること」です。</li>
</ul>

<h3>2. リンクしているもの</h3>
<p>動画・楽曲・記事など、著作物にあたるものは、基本的に公式のものだけにリンクしています。例外は下の「ボカロ曲の原曲」です。</p>
<ul>
  <li><strong>動画</strong>は、公式チャンネルが公開しているYouTube等の動画や、公式Instagramのライブ配信アーカイブにリンクしています。</li>
  <li><strong>楽曲</strong>は、各配信サービス（YouTube Music、Spotify、Apple Music など）の音源にリンクしています。音源がないものは、公式の動画にリンクしている場合があります。</li>
  <li><strong>ボカロ曲の原曲</strong>（ボカロ部など、宮本佳林さんが歌った曲の元の曲）は、ニコニコ動画に投稿されている原曲の動画にリンクしています。公式の動画ではありませんが、その曲の原曲として投稿されている動画（制作者の方ご本人が投稿したものなど）だけを選び、「原曲はこれです」と示すためにリンクを当てています。他人が無断でアップロードしたと思われるものにはリンクしないようにしています。</li>
  <li><strong>公式のインタビュー</strong>などの記事は、Web Archive（web.archive.org）にリンクしています。今のところ、使っているアーカイブサイトはWeb Archiveだけです。</li>
  <li>そのほか、公式サイト、公式SNS、公式ブログ、ラジオ番組のページなどにもリンクしています。</li>
</ul>

<h3>3. 公式以外の情報について</h3>
<p>セットリスト、誕生日、出演作品の情報など、事実にあたる情報は、公式が発表したものだけとは限りません。Wikipedia、セットリストのデータベース、映画のデータベースなど、公式以外の情報サイトも参考にして整理し、リンクしている場合があります。</p>

<h3>4. 載せていないもの</h3>
<ul>
  <li>動画・音声・記事の<strong>再公開（転載・再アップロード）はしていません</strong>。</li>
  <li>ファンの方の発言やブログ、イベントやコンサートの会場での発言・MCの内容などは、載せていません。</li>
</ul>

<h3>5. 「みんなが見られたもの」を集めています</h3>
<p>当サイトがまとめているのは、公開されていて、広く誰でも見られたことのある情報です。たとえば、すでに見られなくなったもの（ニコニコ動画のボカロ部のように期間限定で公開されていた動画、島倉りかのりかわのように今は閲覧できないものなど）も、当時は誰もが見られたものなので、記録として残しています。見られなくなったものは、アーカイブが残っていればそちらにリンクしています。</p>

